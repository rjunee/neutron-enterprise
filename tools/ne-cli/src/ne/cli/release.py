_MEMBER_GLOBS = ("packages", "tools")


def _member_dirs(root: Path) -> list[Path]:
    """Every workspace member directory (contains a pyproject.toml), sorted by path."""
    members: list[Path] = []
    for parent in _MEMBER_GLOBS:
        base = root / parent
        if not base.is_dir():
            continue
        for child in base.iterdir():
            if (child / "pyproject.toml").is_file():
                members.append(child)
    return sorted(members, key=lambda p: p.relative_to(root).as_posix())


def _dist_name(member: Path) -> str:
    data = tomllib.loads((member / "pyproject.toml").read_text(encoding="utf-8"))
    return str(data.get("project", {}).get("name", member.name))


def aggregate_notice(root: Path) -> str:
    """Concatenate every member NOTICE. Raises FileNotFoundError if any is missing."""
    members = _member_dirs(root)
    missing = [m.relative_to(root).as_posix() for m in members if not (m / "NOTICE").is_file()]
    if missing:
        raise FileNotFoundError(
            "workspace members missing a NOTICE file (per-package NOTICE convention): "
            + ", ".join(missing)
        )
    lines = [
        "Aggregate NOTICE — generated by `ne release notice`; DO NOT hand-edit or",
        "commit to the repository root. The per-package NOTICE files are the source",
        "of truth (see CONTRIBUTING.md, 'NOTICE policy').",
        "",
    ]
    for member in members:
        dist = _dist_name(member)
        lines.append(f"=== {dist} ===")
        lines.append((member / "NOTICE").read_text(encoding="utf-8").rstrip("\n"))
        lines.append("")
    return "\n".join(lines) + "\n"


@click.group("release")
def release() -> None:
    """Release-time supply-chain artifacts (NOTICE, SBOM, provenance)."""


@release.command("notice")
@click.option(
    "--out",
    "out",
    type=click.Path(path_type=Path),
    default=Path("dist/NOTICE"),
    show_default=True,
    help="Output path for the aggregated NOTICE.",
)
def notice(out: Path) -> None:
    """Aggregate all per-package NOTICE files into a single release NOTICE."""
    root = _find_repo_root(Path.cwd())
    resolved = out if out.is_absolute() else (Path.cwd() / out)
    # Refuse to write a committed repo-root NOTICE (shared-file policy).
    if resolved.resolve() == (root / "NOTICE").resolve():
        raise click.ClickException(
            "refusing to write the repository-root NOTICE — the per-package "
            "convention forbids a committed root NOTICE; choose an output under dist/."
        )
    try:
        content = aggregate_notice(root)
    except FileNotFoundError as exc:
        raise click.ClickException(str(exc)) from exc
    resolved.parent.mkdir(parents=True, exist_ok=True)
    resolved.write_text(content, encoding="utf-8")
    n = len(_member_dirs(root))
    click.echo(f"wrote {resolved} — aggregated {n} member NOTICE files.")


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


_REQUIRED_ENV = (
    "GITHUB_SERVER_URL",
    "GITHUB_REPOSITORY",
    "GITHUB_REF",
    "GITHUB_SHA",
    "GITHUB_WORKFLOW_REF",
    "GITHUB_RUN_ID",
    "GITHUB_RUN_ATTEMPT",
)


def build_provenance(subjects: list[Path], env: dict[str, str]) -> dict:
    """Build an in-toto Statement with a slsa.dev/provenance/v1 predicate."""
    missing = [k for k in _REQUIRED_ENV if not env.get(k)]
    if missing:
        raise ValueError(f"missing required GITHUB_* environment: {', '.join(missing)}")

    server = env["GITHUB_SERVER_URL"]
    repo = env["GITHUB_REPOSITORY"]
    ref = env["GITHUB_REF"]
    sha = env["GITHUB_SHA"]
    workflow_ref = env["GITHUB_WORKFLOW_REF"]
    run_id = env["GITHUB_RUN_ID"]
    repo_url = f"{server}/{repo}"
    run_url = f"{repo_url}/actions/runs/{run_id}"

    return {
        "_type": "https://in-toto.io/Statement/v1",
        "subject": [{"name": p.name, "digest": {"sha256": _sha256(p)}} for p in subjects],
        "predicateType": "https://slsa.dev/provenance/v1",
        "predicate": {
            "buildDefinition": {
                "buildType": "https://actions.github.io/buildtypes/workflow/v1",
                "externalParameters": {
                    "workflow": workflow_ref,
                    "repository": repo_url,
                    "ref": ref,
                },
                "internalParameters": {
                    "github_run_id": run_id,
                    "github_run_attempt": env["GITHUB_RUN_ATTEMPT"],
                },
                "resolvedDependencies": [
                    {"uri": f"git+{repo_url}@{ref}", "digest": {"gitCommit": sha}}
                ],
            },
            "runDetails": {
                "builder": {"id": f"{server}/{workflow_ref}"},
                "metadata": {"invocationId": run_url},
            },
        },
    }


@release.command("provenance")
@click.option(
    "--subject",
    "subjects",
    type=click.Path(exists=True, path_type=Path),
    multiple=True,
    required=True,
    help="Artifact file(s) to record as provenance subjects.",
)
@click.option(
    "--out",
    "out",
    type=click.Path(path_type=Path),
    required=True,
    help="Output path for the in-toto/SLSA-v1 statement JSON.",
)
def provenance(subjects: tuple[Path, ...], out: Path) -> None:
    """Emit an in-toto/SLSA-v1 provenance statement for built artifacts."""
    try:
        statement = build_provenance(list(subjects), dict(os.environ))
    except ValueError as exc:
        raise click.ClickException(str(exc)) from exc
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(statement, indent=2) + "\n", encoding="utf-8")
    click.echo(f"wrote {out} — SLSA v1 provenance for {len(subjects)} subject(s).")


_GITHUB_REPOSITORY = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+\Z")
_GIT_SHA = re.compile(r"[0-9a-f]{40}\Z")
_GITHUB_TIMESTAMP = "%Y-%m-%dT%H:%M:%SZ"
_CHECK_RUN_STATUSES = {"completed", "in_progress", "pending", "queued", "requested", "waiting"}
_CHECK_RUN_CONCLUSIONS = {
    "action_required",
    "cancelled",
    "failure",
    "neutral",
    "skipped",
    "stale",
    "startup_failure",
    "success",
    "timed_out",
}


class _CheckRun(NamedTuple):
    run_id: int
    name: str
    head_sha: str
    status: str
    conclusion: str | None
    started_at: str | None
    completed_at: str | None
    app_id: int
    app_slug: str


def _canonical_json(value: object) -> bytes:
    try:
        encoded = json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        )
    except (TypeError, ValueError) as exc:
        raise ValueError("GitHub returned non-canonical JSON metadata") from exc
    return encoded.encode("utf-8")


def _json_sha256(value: object) -> str:
    return "sha256:" + hashlib.sha256(_canonical_json(value)).hexdigest()


def _github_api(endpoint: str, paginate: bool) -> object:
    """Read one GitHub REST surface without putting an auth token in argv."""
    command = [
        "gh",
        "api",
        "--method",
        "GET",
        "--header",
        "Accept: application/vnd.github+json",
        "--header",
        "X-GitHub-Api-Version: 2022-11-28",
    ]
    if paginate:
        # --slurp preserves every page as a distinct outer-array member.  The
        # parsers below require that envelope, so accidentally removing this
        # flag cannot silently turn page one into complete authority.
        command.extend(("--paginate", "--slurp"))
    command.append(endpoint)
    try:
        result = subprocess.run(command, capture_output=True, text=True, check=False)
    except FileNotFoundError as exc:
        raise ValueError("GitHub CLI `gh` is required to read required-CI evidence") from exc
    if result.returncode != 0:
        # Do not relay stderr: authentication failures and wrappers are allowed
        # to contain sensitive details.  The endpoint itself contains only the
        # caller-supplied repository and commit identity.
        raise ValueError(f"GitHub API read failed for {endpoint} (exit {result.returncode})")
    try:
        payload: object = json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise ValueError(f"GitHub API returned malformed JSON for {endpoint}") from exc
    if paginate and not isinstance(payload, list):
        raise ValueError(f"GitHub API omitted the pagination envelope for {endpoint}")
    return payload


def _mapping(value: object, label: str) -> dict[str, object]:
    if not isinstance(value, dict) or not all(isinstance(key, str) for key in value):
        raise ValueError(f"malformed GitHub response: {label} must be an object")
    return value


def _array(value: object, label: str) -> list[object]:
    if not isinstance(value, list):
        raise ValueError(f"malformed GitHub response: {label} must be an array")
    return value


def _positive_int(value: object, label: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise ValueError(f"malformed GitHub response: {label} must be a positive integer")
    return value


def _nonempty_string(value: object, label: str) -> str:
    if not isinstance(value, str) or not value or value != value.strip():
        raise ValueError(f"malformed GitHub response: {label} must be a non-empty string")
    return value


def _validate_main_ref(payload: object, subject_sha: str) -> None:
    response = _mapping(payload, "main ref")
    if response.get("ref") != "refs/heads/main":
        raise ValueError("GitHub main-ref response does not identify refs/heads/main")
    target = _mapping(response.get("object"), "main ref object")
    if target.get("type") != "commit":
        raise ValueError("GitHub main ref does not point directly to a commit")
    live_sha = target.get("sha")
    if not isinstance(live_sha, str) or _GIT_SHA.fullmatch(live_sha) is None:
        raise ValueError("malformed GitHub response: main ref SHA is not a full commit SHA")
    if live_sha != subject_sha:
        raise ValueError(
            f"subject SHA {subject_sha} is not the exact final main SHA (live main is {live_sha})"
        )


def _required_status_checks(payload: object) -> list[tuple[str, int]]:
    pages = _array(payload, "effective-rules pagination envelope")
    if not pages:
        raise ValueError("GitHub effective-rules response contained no pages")

    required: set[tuple[str, int]] = set()
    for page_number, raw_page in enumerate(pages, start=1):
        page = _array(raw_page, f"effective-rules page {page_number}")
        for rule_number, raw_rule in enumerate(page, start=1):
            rule = _mapping(raw_rule, f"effective-rules page {page_number} rule {rule_number}")
            rule_type = _nonempty_string(
                rule.get("type"), f"effective-rules page {page_number} rule {rule_number} type"
            )
            if rule_type != "required_status_checks":
                continue
            parameters = _mapping(
                rule.get("parameters"),
                f"effective-rules page {page_number} rule {rule_number} parameters",
            )
            checks = _array(
                parameters.get("required_status_checks"),
                f"effective-rules page {page_number} rule {rule_number} required checks",
            )
            if not checks:
                raise ValueError("effective required-status-check rule contains no checks")
            for check_number, raw_check in enumerate(checks, start=1):
                check = _mapping(raw_check, f"required check {check_number}")
                context = _nonempty_string(
                    check.get("context"), f"required check {check_number} context"
                )
                integration_id = _positive_int(
                    check.get("integration_id"),
                    f"required check {context!r} integration_id",
                )
                required.add((context, integration_id))
    if not required:
        raise ValueError("main has no effective app-bound required status checks")
    return sorted(required)


def _optional_string(value: object, label: str) -> str | None:
    if value is None:
        return None
    return _nonempty_string(value, label)


def _check_runs(payload: object, subject_sha: str) -> list[_CheckRun]:
    pages = _array(payload, "check-runs pagination envelope")
    if not pages:
        raise ValueError("GitHub check-runs response contained no pages")

    total_count: int | None = None
    runs: list[_CheckRun] = []
    seen_ids: set[int] = set()
    for page_number, raw_page in enumerate(pages, start=1):
        page = _mapping(raw_page, f"check-runs page {page_number}")
        page_total = page.get("total_count")
        if isinstance(page_total, bool) or not isinstance(page_total, int) or page_total < 0:
            raise ValueError("malformed GitHub response: check-runs total_count is invalid")
        if total_count is None:
            total_count = page_total
        elif page_total != total_count:
            raise ValueError(
                "ambiguous GitHub response: check-runs total_count changed across pages"
            )
        raw_runs = _array(page.get("check_runs"), f"check-runs page {page_number} runs")
        for run_number, raw_run in enumerate(raw_runs, start=1):
            label = f"check-runs page {page_number} run {run_number}"
            run = _mapping(raw_run, label)
            run_id = _positive_int(run.get("id"), f"{label} id")
            if run_id in seen_ids:
                raise ValueError(f"ambiguous GitHub response: duplicate check-run id {run_id}")
            seen_ids.add(run_id)
            name = _nonempty_string(run.get("name"), f"{label} name")
            head_sha = _nonempty_string(run.get("head_sha"), f"{label} head_sha")
            if _GIT_SHA.fullmatch(head_sha) is None:
                raise ValueError(f"malformed GitHub response: {label} head_sha is not a full SHA")
            if head_sha != subject_sha:
                raise ValueError(
                    f"GitHub returned check run {run_id} for wrong SHA {head_sha}; "
                    f"expected {subject_sha}"
                )
            status = _nonempty_string(run.get("status"), f"{label} status")
            if status not in _CHECK_RUN_STATUSES:
                raise ValueError(
                    f"malformed GitHub response: check run {run_id} has unknown status"
                )
            conclusion = _optional_string(run.get("conclusion"), f"{label} conclusion")
            if conclusion is not None and conclusion not in _CHECK_RUN_CONCLUSIONS:
                raise ValueError(
                    f"malformed GitHub response: check run {run_id} has unknown conclusion"
                )
            app = _mapping(run.get("app"), f"{label} app")
            app_id = _positive_int(app.get("id"), f"{label} app id")
            app_slug = _nonempty_string(app.get("slug"), f"{label} app slug")
            runs.append(
                _CheckRun(
                    run_id=run_id,
                    name=name,
                    head_sha=head_sha,
                    status=status,
                    conclusion=conclusion,
                    started_at=_optional_string(run.get("started_at"), f"{label} started_at"),
                    completed_at=_optional_string(run.get("completed_at"), f"{label} completed_at"),
                    app_id=app_id,
                    app_slug=app_slug,
                )
            )
    if total_count != len(runs):
        raise ValueError(
            "GitHub check-runs pagination is incomplete: "
            f"total_count={total_count}, received={len(runs)}"
        )
    return runs


def _github_timestamp(raw: str | None, label: str) -> datetime:
    if raw is None:
        raise ValueError(f"required check run is missing {label}")
    try:
        return datetime.strptime(raw, _GITHUB_TIMESTAMP).replace(tzinfo=UTC)
    except ValueError as exc:
        raise ValueError(f"required check run has malformed {label}") from exc


def _utc_now() -> datetime:
    return datetime.now(UTC)


def _bind_required_runs(
    required: list[tuple[str, int]],
    runs: list[_CheckRun],
    observation_cutoff: datetime,
) -> list[dict[str, object]]:
    bindings: list[dict[str, object]] = []
    for context, integration_id in required:
        candidates = [run for run in runs if run.name == context and run.app_id == integration_id]
        if not candidates:
            raise ValueError(
                f"missing required check run {context!r} from integration_id {integration_id}"
            )
        # GitHub documents `filter=latest` in terms of time, not numeric id
        # ordering.  Read `filter=all` so a newer queued/failed rerun cannot be
        # hidden behind an older success, then identify the unique newest start.
        dated_candidates = [
            (_github_timestamp(run.started_at, "started_at"), run) for run in candidates
        ]
        latest_started = max(started_at for started_at, _run in dated_candidates)
        latest_candidates = [
            run for started_at, run in dated_candidates if started_at == latest_started
        ]
        if len(latest_candidates) != 1:
            run_ids = sorted(run.run_id for run in latest_candidates)
            raise ValueError(
                f"ambiguous latest required check {context!r} from integration_id "
                f"{integration_id}: check-run ids {run_ids} share started_at"
            )
        latest = latest_candidates[0]
        if latest_started > observation_cutoff:
            raise ValueError(
                f"latest required check {context!r} started after receipt observation cutoff"
            )
        if latest.status != "completed":
            raise ValueError(
                f"latest required check {context!r} from integration_id {integration_id} "
                f"is incomplete ({latest.status})"
            )
        if latest.conclusion != "success":
            raise ValueError(
                f"latest required check {context!r} from integration_id {integration_id} "
                f"is not successful ({latest.conclusion})"
            )
        completed_at = _github_timestamp(latest.completed_at, "completed_at")
        if completed_at < latest_started:
            raise ValueError(f"latest required check {context!r} completed before it started")
        if completed_at > observation_cutoff:
            raise ValueError(
                f"latest required check {context!r} completed after receipt observation cutoff"
            )
        bindings.append(
            {
                "required": {"context": context, "integration_id": integration_id},
                "check_run": {
                    "id": latest.run_id,
                    "name": latest.name,
                    "head_sha": latest.head_sha,
                    "status": latest.status,
                    "conclusion": latest.conclusion,
                    "started_at": latest.started_at,
                    "completed_at": latest.completed_at,
                    "app": {"id": latest.app_id, "slug": latest.app_slug},
                },
            }
        )
    return bindings


def build_required_ci_receipt(
    repository: str,
    subject_sha: str,
    *,
    fetch: Callable[[str, bool], object] | None = None,
) -> dict[str, object]:
    """Read and bind effective final-main required-CI evidence.

    ``fetch`` is an injectable, read-only provider seam used by deterministic
    tests.  It must accept ``(endpoint: str, paginate: bool)``.
    """
    if _GITHUB_REPOSITORY.fullmatch(repository) is None:
        raise ValueError("repository must be an exact OWNER/REPO GitHub name")
    if _GIT_SHA.fullmatch(subject_sha) is None:
        raise ValueError("subject SHA must be exactly 40 lowercase hexadecimal characters")
    provider = _github_api if fetch is None else fetch
    observation_cutoff = _utc_now()

    ref_endpoint = f"repos/{repository}/git/ref/heads/main"
    rules_endpoint = f"repos/{repository}/rules/branches/main?per_page=100"
    checks_endpoint = f"repos/{repository}/commits/{subject_sha}/check-runs?filter=all&per_page=100"

    main_ref_before = provider(ref_endpoint, False)
    _validate_main_ref(main_ref_before, subject_sha)
    rules_pages_before = provider(rules_endpoint, True)
    required_before = _required_status_checks(rules_pages_before)
    check_run_pages_before = provider(checks_endpoint, True)
    runs_before = _check_runs(check_run_pages_before, subject_sha)
    bindings_before = _bind_required_runs(required_before, runs_before, observation_cutoff)
    rules_pages_after = provider(rules_endpoint, True)
    required_after = _required_status_checks(rules_pages_after)
    if required_after != required_before:
        raise ValueError("effective required status checks changed during receipt read")
    check_run_pages_after = provider(checks_endpoint, True)
    runs_after = _check_runs(check_run_pages_after, subject_sha)
    bindings_after = _bind_required_runs(required_after, runs_after, observation_cutoff)
    if _canonical_json(bindings_after) != _canonical_json(bindings_before):
        raise ValueError("selected required check runs changed during receipt read")
    # Close the main-movement race: evidence for an erstwhile main must never
    # be published as the final-main handoff while this read is in flight.
    main_ref_after = provider(ref_endpoint, False)
    _validate_main_ref(main_ref_after, subject_sha)

    response_digest = _json_sha256(
        {
            "main_ref_before": main_ref_before,
            "effective_rules_pages_before": rules_pages_before,
            "check_run_pages_before": check_run_pages_before,
            "effective_rules_pages_after": rules_pages_after,
            "check_run_pages_after": check_run_pages_after,
            "main_ref_after": main_ref_after,
        }
    )
    receipt: dict[str, object] = {
        "schema": "neutron.enterprise.required-ci-receipt/v1",
        "repository": repository,
        "branch": "main",
        "subject_sha": subject_sha,
        "required_checks": bindings_after,
        "response_sha256": response_digest,
    }
    receipt["receipt_sha256"] = _json_sha256(receipt)
    return receipt


def _write_owner_only_atomic(path: Path, receipt: dict[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        dir=path.parent, prefix=f".{path.name}.", suffix=".tmp"
    )
    temporary = Path(temporary_name)
    try:
        os.fchmod(descriptor, 0o600)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(_canonical_json(receipt) + b"\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except Exception:
        temporary.unlink(missing_ok=True)
        raise


@release.command("required-ci-receipt")
@click.option(
    "--repository",
    "--repo",
    required=True,
    help="GitHub repository as OWNER/REPO.",
)
@click.option(
    "--sha",
    "subject_sha",
    required=True,
    help="Exact 40-character final-main commit SHA.",
)
@click.option(
    "--out",
    required=True,
    type=click.Path(path_type=Path, dir_okay=False),
    help="Owner-only canonical JSON receipt path.",
)
def required_ci_receipt(repository: str, subject_sha: str, out: Path) -> None:
    """Read live final-main required CI and emit a metadata-only receipt."""
    try:
        receipt = build_required_ci_receipt(repository, subject_sha)
        _write_owner_only_atomic(out, receipt)
    except (OSError, ValueError) as exc:
        raise click.ClickException(str(exc)) from exc
    click.echo(f"wrote {out} — {receipt['receipt_sha256']}")


