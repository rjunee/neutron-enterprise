"""Release-time supply-chain tooling: NOTICE aggregation and SLSA provenance.

`ne release notice`      — roll the per-package NOTICE files up into a single
                           release NOTICE (never a committed repo-root NOTICE).
`ne release provenance`  — emit an in-toto/SLSA-v1 provenance Statement for a
                           built artifact (signed later with cosign attest-blob).
`ne release sbom`        — bespoke stdlib CycloneDX 1.6 SBOM per workspace member,
                           from uv.lock.
`ne release fingerprint` — the deterministic platform release fingerprint
                           (tag + per-member SBOM + composed config-hash, NE-069).
`ne release bundle`      — the deterministic, versioned release bundle artifact
                           (NE-069).
`ne release push`        — push a locally-built first-party ne-app image to a
                           customer registry and pin it by registry digest
                           (NE-071a — the K8s C11 first-party image pin).
`ne release required-ci-receipt`
                         — bind the effective required checks and their exact
                           successful final-main check runs into one receipt.
"""

