def _worst_cron_gap_seconds(expression: str) -> int:
    """The longest real gap between two fires of ``expression``.

    Evaluated with ``cronsim`` — the SAME parser ``CronScheduler`` fires on — so
    this measures the expression rather than pattern-matching its text.
    """
    from itertools import pairwise

    from cronsim import CronSim

    ticker = CronSim(expression, datetime(2026, 1, 1, tzinfo=UTC))
    fires = [next(ticker) for _ in range(400)]
    return max(int((later - earlier).total_seconds()) for earlier, later in pairwise(fires))


def test_the_salesforce_lane_rotates_inside_its_sla_at_the_cron_it_is_seeded_at() -> None:
    """⭐ POST_DEMO 11 — the quota throttle, and the relation that keeps it safe.

    Salesforce is a free Developer Edition with a hard ~15,000-call daily cap.
    The lane ran ``*/2 * * * *`` (~720 syncs/day) through 2026-09-09 and burned
    the cap out by early afternoon every day — 232 error / 164 success on the
    day this was written, the errors all ``REQUEST_LIMIT_EXCEEDED``.

    The ONLY safe throttle is the sweep CADENCE, because
    ``ne.worker.ingest.authority_sweep_cron`` DERIVES the seeded cron from it:
    the firing gap and the feasibility proof move together and cannot diverge.
    A cron override would break exactly that — ``_seeded_cron`` ranks an explicit
    override ABOVE the derived cron, so the plan would still certify against the
    cadence while the job fired far slower. That is not a throttle but a
    permanent blackout: ``require_points_swept_within_sla`` refuses the whole
    scope on the DB clock once any admitted point ages past the PT1H SLA.

    ⛔ THE RELATION, NOT THE NUMBERS. What is asserted is that a full rotation
    fits strictly inside the contract SLA **at the gap the job is actually
    seeded at** — so a future edit that changed cadence, batch size or the
    point ceiling into an incoherent set fails here even if each number looked
    individually plausible.
    """
    from ne.connect.runner import ConnectSyncSettings
    from ne.connect.salesforce.config import SalesforceConnectorSettings
    from ne.connect.salesforce.contract import (
        salesforce_contract_sla_seconds,
        salesforce_sweep_plan,
    )
    from ne.worker.ingest import _MAX_AUTHORITY_CRON_MINUTES, _seeded_cron

    overlay = {
        **_SF_WRITEBACK_ENV,
        **dict(live._connect_lane_env(live_writeback=True)),
        **dict(live._LIVE_WRITEBACK_AUTHORITY_ENV),
    }
    with patch.dict(os.environ, overlay, clear=True):
        connect = ConnectSyncSettings()
        settings = SalesforceConnectorSettings()

    assert settings.authority_enabled is True
    plan = salesforce_sweep_plan(settings)
    assert plan is not None
    sla = salesforce_contract_sla_seconds(settings)

    cron = _seeded_cron(connect, "salesforce", settings, authority_enabled=True)
    gap = Decimal(_worst_cron_gap_seconds(cron))

    # 1. The declared plan beats the SLA. (True on its own even when the seeded
    #    cron does not — which is precisely why it is not sufficient.)
    plan.require_sub_sla(sla)

    # 2. The job never fires SLOWER than the cadence the plan was proven at.
    #    `authority_sweep_cron` floors and caps the cadence, so it can only ever
    #    fire more often; an override is the one thing that breaks this.
    assert gap <= plan.cadence_seconds, cron

    # 3. ⭐ The load-bearing relation: a full rotation at the REAL firing gap
    #    finishes strictly inside the contract SLA.
    assert plan.batches * (gap + plan.max_batch_duration_seconds) < sla, cron

    # 4. One batch per rotation is what makes (3) reachable at this cadence. A
    #    multi-batch rotation would leave a point unswept for `batches * gap`
    #    seconds, and `require_points_swept_within_sla` refuses the scope on the
    #    DB clock the moment that passes the same SLA.
    assert plan.batch_size >= plan.max_points_per_scope
    assert plan.batches == 1

    # 5. The quota intent: Salesforce is throttled to the SLOWEST cron the
    #    authority sweep permits — 48 syncs/day at the 30-minute ceiling.
    assert gap == 60 * _MAX_AUTHORITY_CRON_MINUTES
    assert 86_400 / int(gap) == 48

    # 6. Salesforce ONLY. m365 has no comparable cap and keeps its 120s cadence.
    with patch.dict(os.environ, {**_M365_WRITEBACK_ENV, **overlay}, clear=True):
        from ne.connect.m365.config import M365ConnectorSettings

        m365 = M365ConnectorSettings()
    m365_gap = Decimal(
        _worst_cron_gap_seconds(_seeded_cron(connect, "m365", m365, authority_enabled=True))
    )
    assert m365_gap == 120 < gap


