def _env_map(env_file: Path) -> dict[str, str]:
    """Parse the staged dotenv file back to a plain dict.

    Values are written single-quoted (Codex C2 — compose-go's env_file dotenv
    parser expands ``$VAR`` and treats an unquoted ``#`` as a comment, so raw
    concatenation corrupts connector values like NE_SALESFORCE_OBJECTS's
    embedded-JSON-quotes shape); unwrap the outer quotes here to recover the
    original value for assertions.
    """
    result: dict[str, str] = {}
    for line in env_file.read_text(encoding="utf-8").splitlines():
        if not line:
            continue
        key, value = line.split("=", 1)
        if len(value) >= 2 and value.startswith("'") and value.endswith("'"):
            value = value[1:-1]
        result[key] = value
    return result


