@pytest.mark.parametrize(
    "url_suffix",
    [
        # -- PATH payloads: accepted by the validator, so the ENCODER must hold.
        '/x"\n      NE_API_INJECTED_KEY: "pwned',  # close the scalar, open a key
        '/x"\n    ne-injected-service:\n      image: "evil',  # a whole service block
        '/x"\r\n      NE_API_INJECTED_KEY: "pwned',  # CRLF
        '/x"\u2028      NE_API_INJECTED_KEY: "pwned',  # unicode line separator (U+2028)
        "/plain/prefix",  # a legitimate proxy path — must survive
        "",
    ],
)
def test_gpu_rerank_url_cannot_inject_yaml_keys_whatever_the_path(
    tmp_path: Path, url_suffix: str
) -> None:
    """Endpoint validation is not an output encoder — this is the encoder's test.

    A URL may legitimately carry a path, so ``validate_in_vpc_endpoint`` accepts
    one; it only rejects a hostile AUTHORITY (the port fails to parse). A path
    containing ``"`` + newline therefore passed validation and, while the value
    was interpolated into a double-quoted YAML scalar, closed that scalar and
    injected arbitrary keys into the ne-api service block — verified, and the
    reason the sibling test above no longer claims to cover this.

    Asserted STRUCTURALLY rather than by exception: parse the overlay and require
    the ne-api environment's key set to be exactly what the non-hostile overlay
    produces plus the three rerank keys, and the services to be exactly the
    expected ones. That holds no matter what the payload tries, and it stays true
    for the benign paths in the same battery (which must still round-trip), so it
    is not satisfiable by a gate that simply refuses everything.
    """
    seed_dir = live._stage_demo_seed(tmp_path)
    baseline_env = _overlay(tmp_path)["services"]["ne-api"]["environment"]

    workdir = tmp_path / f"path-{abs(hash(url_suffix))}"
    workdir.mkdir()
    url = f"http://8.8.8.8:1837{url_suffix}"
    overlay_path = live._write_demo_overlay(workdir, seed_dir, gpu_rerank=url)
    doc = yaml.safe_load(overlay_path.read_text(encoding="utf-8"))

    api_env = doc["services"]["ne-api"]["environment"]
    expected_keys = set(baseline_env) | {
        "NE_API_RERANK_BACKEND",
        "NE_API_TEI_RERANK_URL",
        "NE_API_RERANK_ALLOWED_HOSTS",
    }
    assert set(api_env) == expected_keys, (
        f"the --gpu-rerank value altered the ne-api env key set: "
        f"{sorted(set(api_env) ^ expected_keys)}"
    )
    # The payload survives INSIDE the scalar, escaped — not as YAML structure.
    assert api_env["NE_API_TEI_RERANK_URL"] == url.rstrip("/")
    assert doc["services"].keys() == _overlay(tmp_path)["services"].keys()


