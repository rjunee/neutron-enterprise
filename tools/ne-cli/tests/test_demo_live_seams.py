    assert 401 in unrenewed
    assert held.grants == 1
    first_refusal = unrenewed.index(401)
    assert first_refusal < _ARC_SENDS, "the cadence must actually cross the floor"

    # control: the driver as it now is — every send admitted.
    renewed, renewing = _drive_arc_cadence(renewing=True)
    assert renewed == [200] * _ARC_SENDS
    # ...and it renewed to get there, rather than the fixture being generous.
    assert renewing.grants > 1


