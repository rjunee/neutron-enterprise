def test_stage_connect_dir_is_writable_by_runtime_uid(tmp_path: Path) -> None:
    """The private host workdir must not make the bind root readonly to ne-app."""
    import sqlite3

    workdir = tmp_path / "private-workdir"
    workdir.mkdir(mode=0o700)
    workdir.chmod(0o700)

    connect_dir = live._stage_connect_dir(workdir)

    assert stat.S_IMODE(workdir.stat().st_mode) == 0o700
    connect_stat = connect_dir.stat()
    runtime_uid = 10001
    runtime_gid = 10001
    runtime_can_write = (
        (connect_stat.st_uid == runtime_uid and bool(connect_stat.st_mode & stat.S_IWUSR))
        or (connect_stat.st_gid == runtime_gid and bool(connect_stat.st_mode & stat.S_IWGRP))
        or bool(connect_stat.st_mode & stat.S_IWOTH)
    )
    assert runtime_can_write

    state_db = connect_dir / "state.db"
    with sqlite3.connect(state_db) as connection:
        assert connection.execute("PRAGMA journal_mode=WAL").fetchone() == ("wal",)
        connection.execute("CREATE TABLE state (key TEXT PRIMARY KEY, value TEXT NOT NULL)")
        connection.execute("INSERT INTO state VALUES ('fresh-host', 'ready')")
        connection.commit()
        assert state_db.is_file()
        assert state_db.with_name(f"{state_db.name}-wal").is_file()


