def test_writeback_precheck_never_echoes_a_credential(monkeypatch: pytest.MonkeyPatch) -> None:
    """C12: no credential reaches the pre-check's message.

    The docstring asserted this and NOTHING tested it — review demonstrated that
    switching the error extraction to `include_input=True` reded no test at all.
    A claim that survives the mutation which falsifies it is decoration.

    Plants a distinct sentinel in every credential-bearing variable across all
    three legs, then breaks EACH leg in turn so the message is actually produced,
    and asserts no sentinel appears. Breaking one leg at a time matters: the
    validator reports every failing leg in one message, so a single all-legs-bad
    case would not prove the *passing* legs' secrets stay out.
    """
    sentinels = {
        "NE_SALESFORCE_CLIENT_SECRET": "SF-CANARY-8a1f",
        "NE_M365_CLIENT_SECRET": "M365-CANARY-3d7c",
        "NE_SQL_CONNECTION_URL": "postgresql://ne:SQL-CANARY-5e2b@db/tickets",
    }

    # Each case breaks exactly one leg by REMOVING a required field, so the other
    # two legs validate and their planted secrets must not surface either.
    breakers = ("NE_SALESFORCE_INSTANCE_URL", "NE_M365_TENANT_ID", "NE_SQL_TABLES")

    for broken in breakers:
        _clear_writeback_env(monkeypatch)
        collected: dict[str, str] = {}
        collected.update(_SF_WRITEBACK_ENV)
        collected.update(_M365_WRITEBACK_ENV)
        collected["NE_SQL_TABLES"] = '[{"table": "tickets", "id_column": "id"}]'
        collected.update(sentinels)
        collected.pop(broken, None)

        with pytest.raises(click.ClickException) as caught:
            live._check_writeback_legs(collected)

        message = str(caught.value)
        for var, secret in sentinels.items():
            assert secret not in message, f"{broken}: {var}'s value leaked into {message!r}"
        # CONTROL: the message must still be useful — it names the leg whose
        # absence caused it. Without this, a function returning "" passes above.
        assert "NE_" in message and (
            "sql" in message or "salesforce" in message or "m365" in message
        )


