    # The default (non-gpu-rerank) overlay never carries the trio.
    default_doc = _overlay(tmp_path)
    default_api_env = default_doc["services"]["ne-api"]["environment"]
    for key in ("NE_API_RERANK_BACKEND", "NE_API_RERANK_ALLOWED_HOSTS"):
        assert key not in default_api_env
    assert "NE_API_TEI_RERANK_URL" not in default_api_env


