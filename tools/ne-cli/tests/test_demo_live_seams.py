def test_seed_secret_store_reuses_password_across_reups(tmp_path: Path) -> None:
    """A second `ne demo up` on the same workdir MUST keep the postgres password
    stable — regenerating it desyncs from the persistent pg-data volume and
    crash-loops keycloak (the pg-password-regen bug). Reuse is the fix."""
    store_dir = tmp_path / "secret-store"
    store_dir.mkdir()

    live._seed_secret_store(store_dir)
    pw_first = _read_pg_password(store_dir)
    live._seed_secret_store(store_dir)  # simulate a re-up on the same workdir
    pw_reup = _read_pg_password(store_dir)
    assert pw_reup == pw_first, "postgres password rotated on re-up — pg-data desync"

    # A DIFFERENT workdir gets its own fresh random secret (not hardcoded/shared).
    other = tmp_path / "other-store"
    other.mkdir()
    live._seed_secret_store(other)
    assert _read_pg_password(other) != pw_first


def test_seed_secret_store_uses_stable_fresh_256_bit_authority_key(tmp_path: Path) -> None:
    """Continuation key identity and material survive a same-workdir re-up.

    A new workdir gets a different pair, and the HMAC material is exactly the
    unpadded canonical base64url shape produced by ``token_urlsafe(32)``.
    """
    store_dir = tmp_path / "secret-store"
    store_dir.mkdir()
    live._seed_secret_store(store_dir)
    first = _read_authority_continuation_secret(store_dir)

    live._seed_secret_store(store_dir)
    assert _read_authority_continuation_secret(store_dir) == first

    material = first["hmac_key_b64"]
    assert "=" not in material
    decoded = base64.urlsafe_b64decode(material + "=" * (-len(material) % 4))
    assert len(decoded) == 32

    other = tmp_path / "other-store"
    other.mkdir()
    live._seed_secret_store(other)
    fresh = _read_authority_continuation_secret(other)
    assert fresh["key_id"] != first["key_id"]
    assert fresh["hmac_key_b64"] != material


