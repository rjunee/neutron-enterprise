"""LinkML codegen entrypoint — runs INSIDE the isolated hash-pinned codegen venv.

This module imports `linkml`, which is deliberately NOT part of the platform
virtualenv (its transitive closure contains GPL/CC0/W3C-licensed distributions
that must never enter the platform lock — SPEC §2 C4). It is executed as a
subprocess by ``ne.schema.codegen`` against ``packages/ne-schema/.codegen-venv``.

Given the operational LinkML schema it writes three artifacts to --out-dir:
  * operational.py            — Pydantic models (extra='forbid')
  * operational.schema.json   — JSON Schema (root class OperationalRecordSet)
  * _manifest.py              — schema version + linkml version + source sha256
"""

# pyright: reportMissingImports=false
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

from linkml.generators.jsonschemagen import JsonSchemaGenerator
from linkml.generators.pydanticgen import PydanticGenerator
from linkml.generators.shaclgen import ShaclGenerator
from linkml_runtime import SchemaView
from linkml_runtime.linkml_model.meta import ClassDefinition, SlotDefinition

_LINKML_VERSION = "1.11.1"

_HEADER = "# Copyright (c) 2026 Ryan Junee.\n# SPDX-License-Identifier: Apache-2.0\n"


def _generated_banner(schema_path: Path) -> str:
    return (
        "# ruff: noqa\n"
        f"# GENERATED by `ne schema generate` from src/ne/schema/schemas/{schema_path.name}\n"
        "# DO NOT EDIT — edit the LinkML source and regenerate.\n"
    )


def _normalize_source_path(body: str, schema_path: Path) -> str:
    # linkml embeds the absolute source path in the module-level linkml_meta.
    # Rewrite it to a stable, repo-relative string so the committed artifact is
    # byte-identical regardless of the checkout location (the freshness gate
    # compares bytes on CI).
    canonical = f"packages/ne-schema/src/ne/schema/schemas/{schema_path.name}"
    for variant in {str(schema_path), str(schema_path.resolve()), str(schema_path.absolute())}:
        body = body.replace(variant, canonical)
    return body


def _schema_version(schema_path: Path) -> str:
    """Extract the `version:` field from the LinkML YAML by regex.

    Avoids importing a YAML parser here; the version line is a simple top-level
    scalar. Matches the same regex the platform-side versioning test uses.
    """
    text = schema_path.read_text(encoding="utf-8")
    match = re.search(r"(?m)^version:\s*(\S+)\s*$", text)
    if match is None:  # pragma: no cover - schema always carries a version
        raise ValueError(f"no `version:` field found in {schema_path}")
    return match.group(1)


def _generate_pydantic(schema_path: Path, out_path: Path) -> None:
    gen = PydanticGenerator(str(schema_path), extra_fields="forbid")
    body = _normalize_source_path(gen.serialize(), schema_path)
    if "linkml_runtime" in body:  # pragma: no cover - guarded; would be a defect
        raise RuntimeError(
            "generated Pydantic output imports linkml_runtime; the platform venv "
            "does not ship linkml_runtime — codegen must emit stdlib+pydantic only"
        )
    out_path.write_text(_HEADER + _generated_banner(schema_path) + body, encoding="utf-8")


def _generate_json_schema(schema_path: Path, out_path: Path, top_class: str) -> None:
    gen = JsonSchemaGenerator(
        str(schema_path),
        mergeimports=True,
        top_class=top_class,
        not_closed=False,
    )
    body = gen.serialize()
    if not body.endswith("\n"):
        body += "\n"
    out_path.write_text(body, encoding="utf-8")


def _shacl_banner(schema_path: Path) -> str:
    return (
        "# Copyright (c) 2026 Ryan Junee.\n"
        "# SPDX-License-Identifier: Apache-2.0\n"
        f"# GENERATED by `ne schema generate` from src/ne/schema/schemas/{schema_path.name}\n"
        "# DO NOT EDIT — edit the LinkML source and regenerate.\n"
        "# SHACL shapes (closed) — sorted, blank-node-canonicalized N-Triples for a\n"
        "# byte-stable committed artifact (valid Turtle: N-Triples is a Turtle subset).\n"
    )


def _generate_shacl(schema_path: Path, out_path: Path) -> None:
    """Generate closed SHACL shapes, byte-canonicalized for the freshness gate.

    linkml's ``ShaclGenerator`` output is NOT process-stable: ``sh:ignoredProperties``
    collection order and blank-node object order vary across runs. We (1) sort each
    ``sh:ignoredProperties`` RDF list, (2) run rdflib's canonical-graph algorithm to
    assign deterministic blank-node labels, and (3) emit sorted N-Triples. The
    result is byte-identical across processes so the committed artifact passes the
    determinism + freshness gates.
    """
    from rdflib import Graph
    from rdflib.collection import Collection
    from rdflib.compare import to_canonical_graph
    from rdflib.namespace import Namespace

    sh = Namespace("http://www.w3.org/ns/shacl#")
    raw = ShaclGenerator(str(schema_path), closed=True).serialize()
    graph = Graph()
    graph.parse(data=raw, format="turtle")
    for _s, _p, list_root in list(graph.triples((None, sh.ignoredProperties, None))):
        collection = Collection(graph, list_root)
        members = sorted(collection, key=str)
        collection.clear()
        for member in members:
            collection.append(member)
    canonical = to_canonical_graph(graph)
    lines = sorted(line for line in canonical.serialize(format="nt").splitlines() if line.strip())
    body = "\n".join(lines) + "\n"
    out_path.write_text(_shacl_banner(schema_path) + body, encoding="utf-8")


def _generate_manifest(schema_path: Path, out_path: Path) -> None:
    version = _schema_version(schema_path)
    source_sha256 = hashlib.sha256(schema_path.read_bytes()).hexdigest()
    body = (
        f'"""Generated schema manifest — see {schema_path.name}."""\n\n'
        f'SCHEMA_VERSION = "{version}"\n'
        f'LINKML_VERSION = "{_LINKML_VERSION}"\n'
        f'SOURCE_SHA256 = "{source_sha256}"\n'
    )
    out_path.write_text(_HEADER + "# ruff: noqa\n" + body, encoding="utf-8")


# ---------------------------------------------------------------------------
# Tier-2 entity-graph contracts (NE-081): a 4th, additive artifact type.
#
# For each concrete OperationalEntity subclass this emits a frozen pydantic
# ``<Class>Entity`` model whose fields are the identity + provenance + own
# scalar attributes MINUS the ``inlined: false`` relationship slots, and derives
# ``EDGE_DEFS`` (one per relationship slot) + the ENTITY_CLASSES/EDGE_KINDS
# allowlists the Tier-2 cypher builder validates identifiers against. The graph
# and the schema therefore cannot drift — both come from this one LinkML source.
# ---------------------------------------------------------------------------

#: LinkML scalar range -> python type used in the emitted entity contracts.
_SCALAR_TYPES: dict[str, str] = {
    "string": "str",
    "integer": "int",
    "boolean": "bool",
    "datetime": "datetime",
    "decimal": "Decimal",
    "date": "date",
    "float": "float",
}


def _is_relationship_slot(slot: SlotDefinition) -> bool:
    """A relationship (edge) slot is a class-ranged ``inlined: false`` reference."""
    return slot.inlined is False


def _edge_kind(slot_name: str) -> str:
    return slot_name.upper()


def _python_type(slot: SlotDefinition, enum_names: frozenset[str]) -> str:
    range_name = str(slot.range) if slot.range is not None else "string"
    if range_name in enum_names:
        return range_name
    return _SCALAR_TYPES.get(range_name, "str")


def _field_line(name: str, py_type: str, slot: SlotDefinition) -> str:
    required = bool(slot.required)
    constraints: list[str] = []
    if slot.pattern:
        constraints.append(f'pattern=r"{slot.pattern}"')
    if slot.minimum_value is not None:
        constraints.append(f"ge={slot.minimum_value}")
    default = "default=..." if required else "default=None"
    annotation = py_type if required else f"{py_type} | None"
    field_args = ", ".join([default, *constraints])
    return f"    {name}: {annotation} = Field({field_args})"


def _generate_entity_graph(schema_path: Path, out_path: Path) -> None:
    view = SchemaView(str(schema_path))
    all_classes = view.all_classes()
    enum_names = frozenset(view.all_enums())

    # Concrete entity classes: direct subclasses of OperationalEntity, in schema
    # order (Account, Person, Document, Ticket, Order). The abstract base and the
    # tree_root record-set container are skipped.
    entity_classes: list[str] = [
        name
        for name, cdef in all_classes.items()
        if cdef.is_a == "OperationalEntity" and not cdef.abstract
    ]

    # The identity + provenance slots shared by every entity (from the mixin base).
    base_slot_names: list[str] = list(all_classes["OperationalEntity"].slots)

    models: list[str] = []
    edge_lines: list[str] = []
    used_enums: set[str] = set()

    for class_name in entity_classes:
        cdef: ClassDefinition = all_classes[class_name]
        field_lines: list[str] = []

        for slot_name in base_slot_names:
            slot = view.get_slot(slot_name)
            py_type = _python_type(slot, enum_names)
            field_lines.append(_field_line(slot_name, py_type, slot))

        for slot_name, slot in cdef.attributes.items():
            if _is_relationship_slot(slot):
                edge_lines.append(
                    "    EdgeDef("
                    f'"{_edge_kind(slot_name)}", "{class_name}", "{slot_name}", '
                    f'"{slot.range}", {bool(slot.multivalued)}, {bool(slot.required)}),'
                )
                continue
            py_type = _python_type(slot, enum_names)
            if py_type in enum_names:
                used_enums.add(py_type)
            field_lines.append(_field_line(slot_name, py_type, slot))

        body = "\n".join(field_lines)
        models.append(
            f"class {class_name}Entity(_EntityContract):\n"
            f'    """Tier-2 typed node contract for the {class_name} LinkML class."""\n\n'
            f"{body}\n"
        )

    enum_import = ""
    if used_enums:
        enum_import = (
            "\nfrom ne.schema.generated.operational import (\n"
            + "".join(f"    {name},\n" for name in sorted(used_enums))
            + ")\n"
        )

    contracts_map = "\n".join(f'    "{name}": {name}Entity,' for name in entity_classes)
    edge_kinds = sorted(
        {
            _edge_kind(slot_name)
            for class_name in entity_classes
            for slot_name, slot in all_classes[class_name].attributes.items()
            if _is_relationship_slot(slot)
        }
    )
    entity_set = ", ".join(f'"{name}"' for name in entity_classes)
    edge_kind_set = ", ".join(f'"{kind}"' for kind in edge_kinds)

    parts = [
        _HEADER,
        _generated_banner(schema_path),
        "from __future__ import annotations\n\n",
        "from datetime import date, datetime\n",
        "from decimal import Decimal\n",
        "from typing import NamedTuple\n\n",
        "from pydantic import BaseModel, ConfigDict, Field\n",
        enum_import,
        "\n\n",
        "class _EntityContract(BaseModel):\n",
        '    """Frozen base for every generated Tier-2 entity node contract."""\n\n',
        '    model_config = ConfigDict(frozen=True, extra="forbid")\n\n\n',
        "\n\n".join(models),
        "\n\n",
        "class EdgeDef(NamedTuple):\n",
        '    """A typed relation derived from an ``inlined: false`` LinkML slot."""\n\n',
        "    edge_kind: str\n",
        "    subject_class: str\n",
        "    slot_name: str\n",
        "    object_class: str\n",
        "    multivalued: bool\n",
        "    required: bool\n\n\n",
        "EDGE_DEFS: tuple[EdgeDef, ...] = (\n",
        "\n".join(edge_lines),
        "\n)\n\n",
        f"ENTITY_CLASSES: frozenset[str] = frozenset({{{entity_set}}})\n\n",
        f"EDGE_KINDS: frozenset[str] = frozenset({{{edge_kind_set}}})\n\n",
        "ENTITY_CONTRACTS: dict[str, type[_EntityContract]] = {\n",
        contracts_map,
        "\n}\n",
    ]
    out_path.write_text("".join(parts), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate ne-schema artifacts.")
    parser.add_argument("--schema", required=True, type=Path)
    parser.add_argument("--out-dir", required=True, type=Path)
    parser.add_argument("--top-class", required=True)
    parser.add_argument("--manifest-name", required=True)
    parser.add_argument("--graph-name", default=None)
    parser.add_argument("--shacl-name", default=None)
    args = parser.parse_args()

    schema_path: Path = args.schema
    out_dir: Path = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    stem = schema_path.stem
    _generate_pydantic(schema_path, out_dir / f"{stem}.py")
    _generate_json_schema(schema_path, out_dir / f"{stem}.schema.json", args.top_class)
    _generate_manifest(schema_path, out_dir / args.manifest_name)
    if args.graph_name:
        _generate_entity_graph(schema_path, out_dir / args.graph_name)
    if args.shacl_name:
        _generate_shacl(schema_path, out_dir / args.shacl_name)


if __name__ == "__main__":
    main()
